# ============================================================
# GENERIC SUMMARY FUNCTION
# ============================================================

def summarize_metric(data, group_columns, metric):

    rows = []

    grouped = data.groupby(
        group_columns,
        observed=True
    )

    for groups, subset in grouped:

        values = subset[
            metric
        ].dropna()

        if len(values) == 0:
            continue

        if not isinstance(groups, tuple):
            groups = (groups,)

        row = dict(
            zip(group_columns, groups)
        )

        row.update({
            "metric": metric,
            "n": len(values),

            "mean": values.mean(),
            "std": values.std(),

            "median": values.median(),

            "q25": values.quantile(0.25),
            "q75": values.quantile(0.75),

            "min": values.min(),
            "max": values.max(),
        })

        rows.append(row)

    return rows


# ============================================================
# BOXPLOT FUNCTION
# ============================================================

def make_boxplot(
    data,
    metric,
    filename,
    title,
    ylabel,
    figure_dir,
):

    plot_data = []

    labels = []

    for predictor in PREDICTORS:

        values = data.loc[
            data["predictor"] == predictor,
            metric
        ].dropna()

        if len(values) > 0:

            plot_data.append(
                values.values
            )

            labels.append(
                predictor
            )

    if not plot_data:
        return

    fig, ax = plt.subplots(
        figsize=(9, 6)
    )

    ax.boxplot(
        plot_data,
        labels=labels,
        showfliers=False
    )

    # Overlay individual observations.
    for i, values in enumerate(plot_data, start=1):

        jitter = np.random.normal(
            i,
            0.035,
            size=len(values)
        )

        ax.scatter(
            jitter,
            values,
            alpha=0.35,
            s=10
        )

    ax.set_xlabel(
        "Prediction method"
    )

    if ylabel is None:
        ylabel = metric

    ax.set_ylabel(ylabel)

    ax.set_title(title)

    fig.tight_layout()

    fig.savefig(
        os.path.join(
            figure_dir,
            filename
        ),
        dpi=300,
        bbox_inches="tight"
    )

    plt.close(fig)


# ============================================================
# CATEGORY BOXPLOT FUNCTION
# ============================================================

def make_category_boxplot(
    data,
    metric,
    filename,
    title,
    ylabel,
    figure_dir,
):

    valid = data[
        data[metric].notna()
    ].copy()

    if valid.empty:
        return

    fig, ax = plt.subplots(
        figsize=(12, 7)
    )

    width = 0.14

    category_positions = np.arange(
        len(CATEGORIES)
    )

    # Use Matplotlib's default color cycle.
    colors = plt.rcParams["axes.prop_cycle"].by_key()["color"]

    # Store handles for the legend.
    legend_handles = []

    for predictor_index, predictor in enumerate(PREDICTORS):

        predictor_color = colors[
            predictor_index % len(colors)
        ]

        for category_index, category in enumerate(CATEGORIES):

            values = valid.loc[
                (valid["predictor"] == predictor)
                &
                (valid["category"] == category),
                metric
            ].dropna()

            if len(values) == 0:
                continue

            position = (
                category_index
                + (
                    predictor_index
                    - (len(PREDICTORS) - 1) / 2
                ) * width
            )

            bp = ax.boxplot(
                values.values,
                positions=[position],
                widths=width * 0.8,
                patch_artist=True,
                showfliers=False
            )

            # Colour the box.
            for box in bp["boxes"]:
                box.set_facecolor(predictor_color)
                box.set_alpha(0.7)

            # Colour the median line.
            for median in bp["medians"]:
                median.set_color("black")
                median.set_linewidth(1.5)

            # Colour whiskers and caps.
            for whisker in bp["whiskers"]:
                whisker.set_color(predictor_color)

            for cap in bp["caps"]:
                cap.set_color(predictor_color)

        # Create one legend entry per predictor.
        legend_handles.append(
            plt.Rectangle(
                (0, 0),
                1,
                1,
                facecolor=predictor_color,
                alpha=0.7,
                label=predictor
            )
        )

    ax.set_xticks(
        category_positions
    )

    ax.set_xticklabels(
        CATEGORIES,
        rotation=20,
        ha="right"
    )

    if ylabel is None:
        ylabel = metric

    ax.set_ylabel(ylabel)
    ax.set_xlabel("Complex type")

    ax.set_title(title)

    ax.legend(
        handles=legend_handles,
        title="Prediction method"
    )

    fig.tight_layout()

    fig.savefig(
        os.path.join(
            figure_dir,
            filename
        ),
        dpi=300,
        bbox_inches="tight"
    )

    plt.close(fig)


