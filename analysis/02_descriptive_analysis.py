# SIZE RELATIONSHIP PLOT
# ============================================================

def make_size_relationship_plot(
    data,
    metric,
    filename,
    title,
    ylabel,
    figure_dir,
):
    """
    Plot performance versus structure size.

    Individual observations are shown with low opacity, while
    a LOWESS trend line is shown for each predictor.
    """

    valid = data[
        data["structure_residues"].notna()
        &
        data[metric].notna()
    ].copy()

    if valid.empty:
        return

    fig, ax = plt.subplots(
        figsize=(9, 6)
    )

    # Use Matplotlib's default color cycle so that predictor
    # colours remain consistent across all figures.
    colors = plt.rcParams["axes.prop_cycle"].by_key()["color"]

    for predictor_index, predictor in enumerate(PREDICTORS):

        subset = valid[
            valid["predictor"] == predictor
        ].copy()

        if len(subset) == 0:
            continue

        color = colors[
            predictor_index % len(colors)
        ]

        x = subset["structure_residues"].values
        y = subset[metric].values

        # ----------------------------------------------------
        # Individual observations
        # ----------------------------------------------------

        ax.scatter(
            x,
            y,
            s=18,
            alpha=0.18,
            color=color,
            edgecolors="none"
        )

        # ----------------------------------------------------
        # LOWESS trend
        # ----------------------------------------------------

        if len(subset) >= 5:

            try:

                from statsmodels.nonparametric.smoothers_lowess import (
                    lowess
                )

                order = np.argsort(x)

                x_sorted = x[order]
                y_sorted = y[order]

                smooth = lowess(
                    y_sorted,
                    x_sorted,
                    frac=0.6,
                    it=2,
                    return_sorted=True
                )

                ax.plot(
                    smooth[:, 0],
                    smooth[:, 1],
                    linewidth=2.2,
                    color=color,
                    label=predictor
                )

            except ImportError:

                # Fallback to a simple rolling mean if statsmodels
                # is not available.
                order = np.argsort(x)

                x_sorted = x[order]
                y_sorted = y[order]

                window = max(
                    3,
                    int(len(x_sorted) * 0.15)
                )

                rolling_y = (
                    pd.Series(y_sorted)
                    .rolling(
                        window=window,
                        center=True,
                        min_periods=1
                    )
                    .mean()
                    .values
                )

                ax.plot(
                    x_sorted,
                    rolling_y,
                    linewidth=2.2,
                    color=color,
                    label=predictor
                )

        else:

            ax.plot(
                x,
                y,
                linewidth=2.0,
                color=color,
                label=predictor
            )

    ax.set_xlabel(
        "Structure size (residues)"
    )

    ax.set_ylabel(
        ylabel
    )

    ax.set_title(
        title
    )

    ax.legend(
        title="Prediction method"
    )

    ax.grid(
        alpha=0.2
    )

    fig.tight_layout()

    fig.savefig(
        os.path.join(
            figure_dir,
            filename
        ),
        dpi=300,
        bbox_inches="tight"
    )

    plt.close(fig)


